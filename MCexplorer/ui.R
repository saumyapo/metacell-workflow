wstep <- function(n, title, tag = NULL, ...) div(class = "mcx-wstep",
  div(class = "mcx-wnum", n),
  div(class = "mcx-wbody", div(class = "mcx-wtitle", title, if (!is.null(tag)) span(class = "mcx-wtag", tag)), ...))
next_card <- function(goto, ic, title, text) tags$a(href = "#", class = "mcx-next",
  onclick = sprintf("Shiny.setInputValue('goto','%s',{priority:'event'});return false;", goto),
  div(class = "mcx-next-icon", icon(ic)), div(class = "mcx-next-text", div(class = "t", title), div(class = "s", text)), icon("arrow-right", class = "mcx-next-arrow"))

